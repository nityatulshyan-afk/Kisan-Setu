let currentLang = localStorage.getItem('kisansetu_lang') || 'hi';

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('kisansetu_lang', lang);
    if (window.dispatchEvent) {
      window.dispatchEvent(new CustomEvent('kisansetu_lang_changed', { detail: { lang } }));
    }
  }
}

function getStoredLanguage() {
  return localStorage.getItem('kisansetu_lang') || 'hi';
}

function t(key) {
  const langObj = translations[currentLang] || translations.en;
  return langObj[key] || translations.en[key] || key;
}

window.I18N = {
  translations,
  get currentLang() {
    return currentLang;
  },
  set currentLang(val) {
    setLanguage(val);
  },
  setLanguage,
  getStoredLanguage,
  t
};

